// Generates src/data/omm-snapshot.mjs from CelesTrak OMM JSON, filtered to the mission catalog.
//   node tools/update-snapshot.mjs --input <omm.json> [--fetched-at <ISO>]   (offline, from a saved download)
//   node tools/update-snapshot.mjs --live                                    (ONE request; CelesTrak allows one download per update)
import { readFileSync, writeFileSync } from 'node:fs';
import { MISSIONS } from '../src/data/missions.mjs';
import { toSatrec } from '../src/core/sgp4.mjs';

export const GROUP_URL = 'https://celestrak.org/NORAD/elements/gp.php?NAME=SENTINEL&FORMAT=JSON';
const OUT = new URL('../src/data/omm-snapshot.mjs', import.meta.url);

/** Keep only catalog missions; throw (naming the NORAD ID) when a record does not build a valid satrec. */
export function buildSnapshot(records, fetchedAt) {
  const wanted = new Set(MISSIONS.map((m) => m.norad));
  const kept = records.filter((r) => wanted.has(r.NORAD_CAT_ID)).sort((a, b) => a.NORAD_CAT_ID - b.NORAD_CAT_ID);
  for (const r of kept) {
    const s = toSatrec(r);
    if (s.failed) throw new Error(`NORAD ${r.NORAD_CAT_ID} produced an invalid satrec (${s.reason})`);
  }
  return { fetchedAt, records: kept };
}

/** Exactly one request, no retry. */
export async function fetchRecords(fetchFn = fetch) {
  const res = await fetchFn(GROUP_URL);
  if (!res.ok) throw new Error(`CelesTrak responded HTTP ${res.status}; not retrying`);
  return res.json();
}

export function renderModule(snapshot) {
  const rows = snapshot.records.map((r) => `    ${JSON.stringify(r)},`).join('\n');
  return `// GENERATED by tools/update-snapshot.mjs - do not edit by hand.
export const SNAPSHOT = {
  fetchedAt: ${JSON.stringify(snapshot.fetchedAt)},
  records: [
${rows}
  ],
};
`;
}

async function main(argv) {
  const arg = (name) => argv[argv.indexOf(name) + 1];
  let records;
  let fetchedAt = arg('--fetched-at') ?? new Date().toISOString();
  if (argv.includes('--live')) {
    records = await fetchRecords();
    fetchedAt = new Date().toISOString();
  } else if (argv.includes('--input')) {
    records = JSON.parse(readFileSync(arg('--input'), 'utf8'));
  } else {
    throw new Error('Pass --input <omm.json> or --live');
  }
  const snap = buildSnapshot(records, fetchedAt);
  writeFileSync(OUT, renderModule(snap));
  console.log(`Wrote ${snap.records.length} records (fetchedAt ${fetchedAt})`);
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2)).catch((e) => (console.error(e.message), process.exit(1)));
