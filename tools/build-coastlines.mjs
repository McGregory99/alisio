// Dev-time tool: builds src/data/coastlines.mjs from Natural Earth 110m land (public domain, naturalearthdata.com).
// Usage: node tools/build-coastlines.mjs [path-to-ne_110m_land.geojson]   (downloads the file when no path is given)
// The downloaded data is untrusted input: every coordinate is checked to be a finite number inside the lon/lat range
// before anything is written. Output is simplified and rounded to 1 decimal to stay near 60 KB.
import { readFile, writeFile } from 'node:fs/promises';
import { simplifyRing, ringAreaDeg2 } from '../src/scene/space-math.mjs';

const URL_110M = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const OUT = new URL('../src/data/coastlines.mjs', import.meta.url);
const BUDGET_BYTES = 60_000;
const MIN_AREA_DEG2 = 1.2; // drop specks that do not read on a globe

/** Exterior rings of a FeatureCollection of Polygon/MultiPolygon as arrays of [lon, lat]; throws on bad input. */
export function ringsFromGeoJson(json) {
  if (json?.type !== 'FeatureCollection' || !Array.isArray(json.features)) throw new Error('not a FeatureCollection');
  const rings = [];
  const take = (poly) => {
    const ring = poly[0]; // exterior ring only: holes are not part of the 110m land set
    if (!Array.isArray(ring)) throw new Error('bad polygon');
    rings.push(ring.map((c) => {
      const lon = Number(c?.[0]), lat = Number(c?.[1]);
      if (!Number.isFinite(lon) || !Number.isFinite(lat) || Math.abs(lon) > 180 || Math.abs(lat) > 90) throw new Error(`bad coordinate ${JSON.stringify(c)}`);
      return [lon, lat];
    }));
  };
  for (const f of json.features) {
    const g = f?.geometry;
    if (g?.type === 'Polygon') take(g.coordinates);
    else if (g?.type === 'MultiPolygon') g.coordinates.forEach(take);
    else throw new Error(`unsupported geometry ${g?.type}`);
  }
  return rings;
}

const round1 = (v) => Math.round(v * 10) / 10;

export function build(rings, tol) {
  const out = [];
  for (const r of rings) {
    if (ringAreaDeg2(r) < MIN_AREA_DEG2) continue;
    const s = simplifyRing(r, tol).map(([lon, lat]) => [round1(lon), round1(lat)]);
    if (s.length >= 3) out.push(s);
  }
  return out;
}

export const render = (rings) => `// GENERATED by tools/build-coastlines.mjs - do not edit by hand.
// Natural Earth 110m land (public domain, https://www.naturalearthdata.com/), simplified. Rings of [lon, lat] degrees.
export const COASTLINES = [
${rings.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
];
`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const src = process.argv[2];
  const text = src ? await readFile(src, 'utf8') : await (await fetch(URL_110M)).text();
  const rings = ringsFromGeoJson(JSON.parse(text));
  let tol = 0.05, out;
  for (; tol < 3; tol += 0.05) { out = render(build(rings, tol)); if (Buffer.byteLength(out) <= BUDGET_BYTES) break; }
  await writeFile(OUT, out);
  console.log(`coastlines: ${build(rings, tol).length} rings, tolerance ${tol.toFixed(2)} deg, ${Buffer.byteLength(out)} bytes`);
}
